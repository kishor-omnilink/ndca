"""
Inventory synchronization result.

Contains the statistics generated by one inventory synchronization run.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(slots=True)
class SyncResult:
    """Statistics and outcome of an inventory synchronization."""

    sync_id: str
    total_discovered: int = 0
    created: int = 0
    updated: int = 0
    deactivated: int = 0
    unchanged: int = 0
    failed: int = 0
    status: str = "SUCCESS"

    @property
    def processed(self) -> int:
        """Return the number of successfully processed elements."""
        return self.created + self.updated + self.unchanged